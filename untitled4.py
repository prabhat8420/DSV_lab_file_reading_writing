import pandas as pd

# Path to the titanic CSV
file_path = '/content/titanic.csv'
'''
We will compute the mean of the 'Fare'
column grouped by 'Pclass' (passenger class)
Since we are processing in chunks, we aggregate
the sum and count per class for each chunk

'''
sums = pd.Series(dtype=float)
counts = pd.Series(dtype=int)

'''
Read in chunks of 2,000 rows (titanic.csv is small,
but this demonstrates the chunk logic)

'''
chunksize = 2000
for chunk in pd.read_csv(file_path, chunksize=chunksize):
    # Group by Pclass and aggregate sum and count of Fare
    grouped = chunk.groupby('Pclass')['Fare'].agg(['sum', 'count'])

    # Update global running sums and counts
    sums = sums.add(grouped['sum'], fill_value=0)
    counts = counts.add(grouped['count'], fill_value=0)

# Compute final mean across all chunks
final_mean = sums / counts
print("Mean of 'Fare' per 'Pclass' across all chunks:")
print(final_mean)

