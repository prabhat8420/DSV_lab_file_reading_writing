"""### Loading Data with Advanced Parameters

We will use `pd.read_csv` to read our file with custom configurations using these parameters:
* `sep`: Separator/delimiter (e.g. `|` for pipe-delimited).
* `header`: Row number(s) to use as column names.
* `names`: Custom list of column names to use.
* `index_col`: Column to use as the row labels of the DataFrame.
* `usecols`: Return a subset of the columns.
* `nrows`: Number of rows of file to read.
* `skiprows`: Line numbers to skip or number of lines to skip at the start.
"""

# Demonstrate pd.read_csv using advanced parameters
# We will read from 'AB_index.txt' (which is pipe-separated)
custom_df = pd.read_csv(
    filepath_or_buffer='AB_index.txt',
    sep='|',
    header=0,  # Use the first row as the original header, but we will override it with `names`
    names=['Col_A', 'Col_B', 'Col_C', 'Col_D', 'Col_E', 'Col_F', 'Col_G'], # Rename columns
    index_col='Col_A', # Set the renamed 'Col_A' as our DataFrame index
    usecols=['Col_A', 'Col_B', 'Col_C', 'Col_D'], # Only load a subset of columns (including the index column)
    skiprows=1, # Skip the first row (the original header 'A|B|C|D|E|F|G') since we are providing our own names
    nrows=5 # Read only the first 5 data rows
)

display(custom_df)

